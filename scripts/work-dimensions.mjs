// Reads the pixel size of every image in public/work and writes
// src/lib/work-dimensions.ts so portfolio cards can show each graphic
// uncropped at its natural aspect ratio. Run after adding work images:
//   npm run dims
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve("public");
const dir = path.join(root, "work");
const exts = new Set([".webp", ".jpg", ".jpeg", ".png", ".avif"]);

async function walk(d) {
  const out = [];
  for (const e of await readdir(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (exts.has(path.extname(e.name).toLowerCase())) out.push(p);
  }
  return out;
}

const files = (await walk(dir)).sort();
const entries = [];
for (const f of files) {
  const { width, height } = await sharp(f).metadata();
  const url = "/" + path.relative(root, f).split(path.sep).join("/");
  entries.push(`  ${JSON.stringify(url)}: [${width}, ${height}],`);
}

await writeFile(
  "src/lib/work-dimensions.ts",
  `/* Generated by scripts/work-dimensions.mjs — run \`npm run dims\` after adding work images. */\nexport const workDimensions: Record<string, [number, number]> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`work-dimensions: ${entries.length} images`);
